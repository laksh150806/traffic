// Joins every migration, in order, into supabase/setup.sql: one file to paste into the
// Supabase SQL editor on a brand-new project. The migrations stay the source of truth;
// run `npm run build:setup` after adding one.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "supabase", "migrations");
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const parts = [
  "-- Smart Traffic Management: full database setup for a NEW, EMPTY Supabase project.",
  "-- Generated by scripts/build-setup-sql.mjs from supabase/migrations. Do not edit by hand.",
  "-- Paste the whole file into the Supabase SQL editor and run it once. It creates the schema,",
  "-- the 69 Chennai junctions with their roads, signals and cameras, the control functions,",
  "-- the phase-change trigger and the views the dashboard reads.",
  "",
];
for (const file of files) {
  const sql = fs.readFileSync(path.join(dir, file), "utf8").replace(/\r\n/g, "\n").trim();
  if (!sql) continue;
  parts.push(`-- ---------------------------------------------------------------------------`);
  parts.push(`-- ${file}`);
  parts.push(`-- ---------------------------------------------------------------------------`);
  parts.push(sql);
  parts.push("");
}

fs.writeFileSync(path.join(root, "supabase", "setup.sql"), parts.join("\n"));
console.log(`supabase/setup.sql written from ${files.length} migrations`);
