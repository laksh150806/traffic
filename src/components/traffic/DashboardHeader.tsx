import { useEffect, useState, type CSSProperties } from "react";
import { Download, Link2, Play, RefreshCw } from "lucide-react";
import type { DataMode } from "@/lib/data-mode";
import type { LiveTraffic } from "@/components/ops/useLiveTraffic";

function timeAgo(iso: string | null) {
  if (!iso) return "waiting for data";
  const seconds = Math.max(0, Math.round((Date.now() - new Date(iso).getTime()) / 1000));
  if (seconds < 60) return `${seconds}s ago`;
  const minutes = Math.round(seconds / 60);
  if (minutes < 60) return `${minutes} min ago`;
  return `${Math.round(minutes / 60)} h ago`;
}

/** A segmented ring that turns while the system is live: the same idea as the control-room dial, small. */
function Mark() {
  return (
    <svg viewBox="0 0 64 64" className="ring-mark h-9 w-9" aria-hidden>
      <g className="ring-outer" fill="none" stroke="var(--primary)" strokeWidth="2.2">
        <circle cx="32" cy="32" r="28" strokeDasharray="30 8 12 8" opacity="0.9" />
      </g>
      <g className="ring-inner" fill="none" stroke="var(--primary)" strokeWidth="1.4">
        <circle cx="32" cy="32" r="20" strokeDasharray="4 5" opacity="0.6" />
      </g>
      <circle cx="32" cy="32" r="6" fill="var(--stark-red)" />
      <circle
        cx="32"
        cy="32"
        r="11"
        fill="none"
        stroke="var(--stark-red)"
        strokeWidth="1"
        opacity="0.5"
      />
    </svg>
  );
}

export function DashboardHeader({
  lastUpdated,
  onRecalculate,
  busy,
  mode,
  onStartTour,
  tourPlaying = false,
  onShare,
  shareLabel = "Share view",
  onExport,
  liveTraffic,
  trafficDriving = true,
}: {
  lastUpdated: string | null;
  onRecalculate: () => void;
  busy: boolean;
  mode: DataMode;
  onStartTour?: () => void;
  tourPlaying?: boolean;
  onShare?: () => void;
  shareLabel?: string;
  onExport?: () => void;
  /** Whether real TomTom speeds are driving the simulation. */
  liveTraffic?: LiveTraffic;
  /** False while a made-up scenario (rush hour, overnight) is in charge of the simulated demand. */
  trafficDriving?: boolean;
}) {
  const simulated = mode === "simulated";
  const real =
    liveTraffic && (liveTraffic.status === "live" || liveTraffic.status === "stale")
      ? liveTraffic
      : null;
  // Re-render now and then so "Updated 12s ago" keeps counting between data refreshes.
  const [, setTick] = useState(0);
  useEffect(() => {
    const id = window.setInterval(() => setTick((t) => t + 1), 5000);
    return () => window.clearInterval(id);
  }, []);
  return (
    <header className="hud-bar relative z-[600] flex flex-wrap items-center justify-between gap-x-4 gap-y-2 px-4 py-3 md:px-5 lg:absolute lg:inset-x-0 lg:top-0">
      <div className="flex items-center gap-3">
        <Mark />
        <div>
          <h1 className="font-brand text-[0.7rem] uppercase leading-tight tracking-[0.18em] text-foreground md:tracking-[0.36em] md:text-[0.78rem]">
            Smart Traffic Management
          </h1>
          <p className="meta-label leading-tight">Chennai signal control room</p>
        </div>
      </div>

      <div className="flex flex-wrap items-center gap-x-3 gap-y-2">
        <span
          title={
            real
              ? "Real traffic speeds from TomTom set how heavy the demand is at each junction. Queues and signal plans are then computed by the model, because Chennai has no public signal or sensor feed. Traffic data © TomTom."
              : simulated
                ? "No backend is connected. Traffic readings come from a built-in demand simulator, and the signal model runs on top of it."
                : "Connected to the database. Vehicle readings are still generated by a demand simulator because Chennai has no public sensor feed."
          }
          className="glass-chip flex items-center gap-2 whitespace-nowrap px-3.5 py-1.5 text-xs text-foreground"
        >
          <span
            className={`h-1.5 w-1.5 rounded-full signal-live ${
              real?.status === "live" ? "bg-signal-low" : real ? "bg-signal-moderate" : "bg-primary"
            }`}
          />
          {real
            ? real.status === "stale"
              ? "Live traffic, last reading kept"
              : trafficDriving
                ? "Live traffic, TomTom"
                : "Scenario in charge, real traffic paused"
            : simulated
              ? "Simulated data"
              : "Live backend, simulated readings"}
        </span>
        <div className="hidden text-right sm:block">
          <p className="meta-label leading-tight">Updated</p>
          <p className="numeric text-xs text-foreground">
            {timeAgo(real ? new Date(real.snapshot.fetchedAtMs).toISOString() : lastUpdated)}
          </p>
        </div>
        {onShare ? (
          <button
            type="button"
            onClick={onShare}
            title="Copy a link to this exact view: junction, time and trip"
            className="glass-chip hidden items-center gap-1.5 px-3.5 py-2 text-xs text-muted-foreground transition-data hover:text-foreground md:inline-flex"
          >
            <Link2 className="h-3.5 w-3.5" aria-hidden />
            <span aria-live="polite">{shareLabel}</span>
          </button>
        ) : null}
        {onExport ? (
          <button
            type="button"
            onClick={onExport}
            title="Download the whole network at the time on the map as a CSV file"
            className="glass-chip hidden items-center gap-1.5 px-3.5 py-2 text-xs text-muted-foreground transition-data hover:text-foreground md:inline-flex"
          >
            <Download className="h-3.5 w-3.5" aria-hidden />
            Export CSV
          </button>
        ) : null}
        {onStartTour ? (
          <button
            type="button"
            onClick={onStartTour}
            disabled={tourPlaying}
            style={{ "--tint": "var(--nebula)" } as CSSProperties}
            className="glass-button inline-flex items-center gap-2 whitespace-nowrap px-4 py-2 text-xs font-semibold disabled:opacity-60"
          >
            <Play className="h-3.5 w-3.5" aria-hidden />
            {tourPlaying ? "Tour running" : "Take the tour"}
          </button>
        ) : null}
        <button
          type="button"
          onClick={onRecalculate}
          disabled={busy}
          className="glass-button inline-flex items-center gap-2 whitespace-nowrap px-4 py-2 text-xs font-semibold disabled:opacity-50"
        >
          <RefreshCw className={`h-3.5 w-3.5 ${busy ? "animate-spin" : ""}`} />
          Recalculate
        </button>
      </div>
    </header>
  );
}
